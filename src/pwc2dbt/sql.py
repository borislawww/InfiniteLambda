"""Render a compiled model as dbt SQL text."""

from .compiler import INCOMPLETE, ModelResult


def render_model(result: ModelResult) -> str:
    header = [
        f"-- Generated by pwc2dbt from mapping {result.mapping}, target instance {result.target_instance}. Do not edit."
    ]
    if result.status == INCOMPLETE:
        header += [
            "--",
            "-- INCOMPLETE: this is not a faithful conversion and is kept out of the dbt project.",
            "-- Missing target columns and the reason for each:",
            *(f"--   {d}" for d in result.diagnostics if d.severity == INCOMPLETE),
            "-- The select list below omits those columns; nothing was replaced by a placeholder.",
        ]
    text = "\n".join(header) + "\n"
    if result.ctes:
        ctes = ",\n\n".join(f"{cte.name} as (\n\n    {cte.body}\n\n)" for cte in result.ctes)
        text += f"\nwith\n\n{ctes}\n\n{result.final}\n"
    return text
